"""JSA Risk Analyzer - the standalone app's shell and three pages, hosted as one portal page.

GENERATED by sync/sync_apps.py from sync/templates/risk_analyzer.py; the other files in this
folder mirror JSA-Dashboards/jsa-risk-analyzer. The standalone app runs its pages under its
own st.navigation (which can't nest inside this portal's) behind its own shared password, so
this wrapper skips both: the portal's login is the only gate, a segmented control switches
between the pages, and each page script runs as-is. The commodity picker and header are the
standalone app.py's, minus its page config and Cloud-badge script. Snowflake and Massive
come from the portal's root-level secrets (jsa_risk/config.py), schema JSA.RISK_ANALYZER.
"""
import runpy
import sys
from pathlib import Path

import streamlit as st

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE / "src"))

from jsa_risk.pricing.commodities import COMMODITIES
from jsa_risk.state import get_commodity_spec, init_session_state, set_commodity
from jsa_risk.ui.theme import render_header_and_disclaimer

st.session_state["authenticated"] = True   # the portal's own login already passed
st.session_state["_embedded"] = True       # add_position asks us, not st.switch_page, to move

init_session_state()


def _on_sidebar_commodity_change() -> None:
    set_commodity(st.session_state["commodity_selector"])


with st.sidebar:
    codes = list(COMMODITIES.keys())
    st.selectbox(
        "Commodity",
        codes,
        index=codes.index(get_commodity_spec().code),
        format_func=lambda c: f"{COMMODITIES[c].icon} {COMMODITIES[c].name} ({c})",
        key="commodity_selector",
        on_change=_on_sidebar_commodity_change,
        help="The dashboard prices one commodity at a time — switching starts a fresh book.",
    )

commodity = get_commodity_spec()
render_header_and_disclaimer(commodity.name)

PAGES = {
    "Risk dashboard": "dashboard.py",
    "Add position": "add_position.py",
    "Import from Excel": "import_excel.py",
}
PAGES = {title: f for title, f in PAGES.items() if (HERE / "pages" / f).exists()}

# A page that wants another one (a saved position -> the dashboard) sets this; it has to be
# applied here, before the control is built, because a widget's value can't be changed after.
_goto = st.session_state.pop("_goto_page", None)
if _goto in PAGES:
    st.session_state["ra_page"] = _goto

choice = st.segmented_control("Risk analyzer page", list(PAGES), default="Risk dashboard",
                              key="ra_page", label_visibility="collapsed") or "Risk dashboard"
runpy.run_path(str(HERE / "pages" / PAGES[choice]), run_name="__main__")
